package vdml.vhdl;

import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeSet;

import vdml.model.Block;
import vdml.model.DiagramModel;
import vdml.model.Direction;
import vdml.model.EntityDef;
import vdml.model.Port;
import vdml.model.Wire;

public final class VhdlEmitter {
    private VhdlEmitter() {
    }

    public static String emitComponentsPackage(DiagramModel model) {
        Set<String> distinct = new TreeSet<>(String.CASE_INSENSITIVE_ORDER);
        for (Block block : model.getBlocks()) {
            distinct.add(block.getEntityName());
        }

        StringBuilder sb = new StringBuilder();
        sb.append(contextClauses(model)).append("\npackage components_pkg is\n");
        for (String entityName : distinct) {
            EntityDef def = model.getEntityCatalog().get(entityName);
            if (def == null) {
                continue;
            }
            sb.append("  component ").append(def.name()).append(" is\n");
            if (!def.generics().isEmpty()) {
                sb.append("    generic (\n");
                appendJoined(sb, def.generics(), "      ", ";");
                sb.append("    );\n");
            }
            if (!def.ports().isEmpty()) {
                sb.append("    port (\n");
                appendJoined(sb, portDecls(def.ports()), "      ", ";");
                sb.append("    );\n");
            }
            sb.append("  end component;\n");
        }
        sb.append("end package components_pkg;\n");
        return sb.toString();
    }

    /** The top-level entity declaration followed by its structural architecture. */
    public static String emitStructuralArchitecture(DiagramModel model) {
        String top = model.getTopEntity();
        StringBuilder sb = new StringBuilder();
        sb.append("-- generated by vdml - do not edit tool-owned regions\n\n");
        sb.append(contextClauses(model)).append('\n');
        sb.append("entity ").append(top).append(" is\n");
        if (!model.getTopGenerics().isEmpty()) {
            sb.append("  generic (\n");
            appendJoined(sb, model.getTopGenerics(), "    ", ";");
            sb.append("  );\n");
        }
        if (!model.getTopPorts().isEmpty()) {
            sb.append("  port (\n");
            appendJoined(sb, portDecls(model.getTopPorts()), "    ", ";");
            sb.append("  );\n");
        }
        sb.append("end entity ").append(top).append(";\n\n");

        sb.append(contextClauses(model)).append("use work.components_pkg.all;\n\n");
        sb.append("architecture structural of ").append(top).append(" is\n\n");

        // One signal per driven net; nets driven by a top-level input use the port itself.
        Map<String, String> signals = new LinkedHashMap<>();
        for (Wire wire : model.getWires()) {
            if (!DiagramModel.TOP_ID.equals(wire.fromBlock())) {
                Port driver = model.endpointPort(wire.fromBlock(), wire.fromPort());
                signals.putIfAbsent(wire.signalName(), driver == null ? "std_logic" : driver.type());
            }
        }
        int width = 0;
        for (String name : signals.keySet()) {
            width = Math.max(width, name.length());
        }
        for (Map.Entry<String, String> e : signals.entrySet()) {
            sb.append("  signal ").append(pad(e.getKey(), width)).append(" : ").append(e.getValue()).append(";\n");
        }
        if (!signals.isEmpty()) {
            sb.append('\n');
        }
        sb.append("  -- [[ USER SIGNALS ]]\n\nbegin\n\n");

        for (Block block : model.getBlocks()) {
            EntityDef def = model.getEntityCatalog().get(block.getEntityName());
            if (def == null) {
                continue;
            }
            sb.append("  ").append(block.getInstanceLabel()).append(" : ").append(def.name()).append('\n');

            List<String> generics = new ArrayList<>();
            for (String formal : def.generics()) {
                String name = EntityDef.genericName(formal);
                String value = block.getGenerics().get(name);
                if (value != null && !value.isBlank()) {
                    generics.add(name + " => " + value);
                }
            }
            if (!generics.isEmpty()) {
                sb.append("    generic map (\n");
                appendJoined(sb, generics, "      ", ",");
                sb.append("    )\n");
            }

            Map<String, String> connected = new LinkedHashMap<>();
            for (Wire wire : model.getWires()) {
                if (wire.toBlock().equals(block.getId())) {
                    connected.put(wire.toPort(), wire.signalName());
                }
                if (wire.fromBlock().equals(block.getId())) {
                    connected.put(wire.fromPort(), wire.signalName());
                }
            }
            int nameWidth = 0;
            for (Port port : def.ports()) {
                nameWidth = Math.max(nameWidth, port.name().length());
            }
            List<String> mapped = new ArrayList<>();
            List<String> open = new ArrayList<>();
            for (Port port : def.ports()) {
                String signal = connected.get(port.name());
                if (signal != null) {
                    mapped.add(pad(port.name(), nameWidth) + " => " + signal);
                } else {
                    open.add("-- " + pad(port.name(), nameWidth) + " => open");
                }
            }
            if (mapped.isEmpty()) {
                // an empty port map is illegal VHDL, so only the commented entries remain
                for (String line : open) {
                    sb.append("    ").append(line).append('\n');
                }
                sb.append("    ;\n");
            } else {
                sb.append("    port map (\n");
                appendJoined(sb, mapped, "      ", ",");
                for (String line : open) {
                    sb.append("      ").append(line).append('\n');
                }
                sb.append("    );\n");
            }
            sb.append('\n');
        }

        for (Port port : model.getTopPorts()) {
            if (port.dir() != Direction.OUT) {
                continue;
            }
            String driver = null;
            for (Wire wire : model.getWires()) {
                if (DiagramModel.TOP_ID.equals(wire.toBlock()) && wire.toPort().equals(port.name())) {
                    driver = wire.signalName();
                }
            }
            sb.append(driver == null ? "  -- " + port.name() + " is not driven\n"
                    : "  " + port.name() + " <= " + driver + ";\n");
        }

        sb.append("\n  -- [[ USER LOGIC ]]\n\nend architecture structural;\n");
        return sb.toString();
    }

    public static String emitAll(DiagramModel model) {
        return emitComponentsPackage(model) + "\n" + emitStructuralArchitecture(model);
    }

    private static List<String> portDecls(List<Port> ports) {
        int width = 0;
        for (Port p : ports) {
            width = Math.max(width, p.name().length());
        }
        List<String> lines = new ArrayList<>();
        for (Port p : ports) {
            lines.add(pad(p.name(), width) + " : " + (p.dir() == Direction.IN ? "in " : "out") + " " + p.type());
        }
        return lines;
    }

    private static String contextClauses(DiagramModel model) {
        StringBuilder sb = new StringBuilder();
        for (String library : model.getLibraries()) {
            sb.append("library ").append(library).append(";\n");
        }
        for (String selectedName : model.getLibraryUses()) {
            sb.append("use ").append(selectedName).append(";\n");
        }
        return sb.toString();
    }

    private static void appendJoined(StringBuilder sb, List<String> lines, String indent, String separator) {
        for (int i = 0; i < lines.size(); i++) {
            sb.append(indent).append(lines.get(i)).append(i < lines.size() - 1 ? separator : "").append('\n');
        }
    }

    private static String pad(String text, int width) {
        return text + " ".repeat(Math.max(0, width - text.length()));
    }
}
